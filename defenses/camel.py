"""
camel.py  —  reimplementation of CaMeL (Debenedetti et al., Google DeepMind,
arXiv:2503.18813, "Defeating Prompt Injections by Design") from the paper's
published capability model (verified against the arXiv PDF: Sections on
provenance/capabilities and Figure 6's policy-function pattern).

CaMeL's real code is public (github.com/google-research/camel-prompt-injection)
but its actual mechanism is a dual-LLM architecture — a Privileged LLM (P-LLM)
that plans by emitting Python-like code, and a Quarantined LLM (Q-LLM) that
handles untrusted data in isolation, executed by a custom interpreter that
attaches capability metadata to every value. Reproducing the interpreter/P-LLM
code-generation pipeline itself is out of scope for LaunderLens (that is
CaMeL's OWN system, not a taint-labelling policy we can replay post-hoc the way
we do for AuthGraph/RTBAS/Fides). What we reimplement is CaMeL's SECURITY
POLICY LAYER — the capability model and the Allowed/Denied check it performs
before a tool call executes — applied post-hoc to an already-generated trace,
exactly like RTBAS's and Fides's own documented post-hoc-replay limitation.

Plain-English idea
-------------------
Every value in CaMeL carries a Capability with two fields (paper's own
description): "Data Provenance: the User (i.e., all literals in the code
generated by the P-LLM), CaMeL itself (i.e., the results of all
transformations done during code execution), or a given tool" and "Allowed
Readers: either the Public singleton (i.e., everyone can access the data), or
a set of users/principals (e.g., identified by their email addresses)."

Security policies are Python functions (paper Figure 6): "Each function takes
the tool name and arguments as input and returns a SecurityPolicyResult
expressed as Allowed or Denied," applied "before executing a tool ... to that
variable and its dependencies, as identified by the dependency graph."

APPROX / scope notes (must be stated in the paper's methods)
--------------------------------------------------------------
1. Post-hoc replay, not live capability propagation through a real
   interpreter. The genuine CaMeL never lets an untrusted value reach a
   consequential tool call in the first place (its custom interpreter
   enforces this DURING code execution, before the call happens). We replay
   the same policy CHECK over an already-generated AgentDojo trace, so we can
   test whether that check, applied to what the (undefended) agent actually
   did, would have been HONEST — not whether CaMeL's real interpreter would
   have prevented the agent from generating that plan at all. Same asymmetry
   already disclosed for RTBAS (defenses/rtbas.py) and Fides (defenses/fides.py).
2. We use TOOL-SOURCE provenance, not full P-LLM/Q-LLM code-level capability
   propagation. CaMeL's real provenance is per-VALUE, tracked through the
   interpreter as code executes (e.g. a string built by concatenating a
   trusted literal with an untrusted tool result becomes "CaMeL"-provenance
   with the join of both inputs' readers). We approximate this the same way
   AuthGraph/RTBAS/Fides do: provenance is assigned per tool OBSERVATION
   (source = which tool produced this content), and a tool call's arguments
   inherit the provenance of whichever observation(s) an LLM judge determines
   they were derived from. This is a real approximation of a system whose
   actual advantage is that provenance is exact by construction (same caveat
   as Fides's APPROX #3) — flagged, not claimed as equivalent.
3. Policy function is a fixed, general rule, not a bespoke per-tool Python
   function as in the paper's Figure 6 example (their calendar-event policy).
   We implement the general shape the paper itself states as the common case:
   a consequential (write) tool call is Denied if any value it depends on has
   provenance whose allowed-readers set does NOT already include (or is not a
   superset compatible with) the call's own principal (the current user) —
   operationalized here as: Denied if any dependency's provenance is a TOOL
   source not on an explicit trust allowlist for that suite (mirroring
   Fides's/RTBAS's untrusted-tool-source convention) UNLESS the value appears
   to have been independently corroborated by a trusted source. Per-tool
   bespoke policies (like the paper's calendar example) are flagged as a
   documented simplification, not attempted here.
4. Known bypass this reimplementation is built to detect: the paper's own
   discussion (Section 6.4, "Data-Flow-to-Control-Flow Conversion") concedes
   CaMeL can be circumvented when "data can influence choice of an action" —
   i.e. when untrusted content is treated as an instruction rather than as
   inert data. Our attacks (attribution forgery, label join) are a DIFFERENT
   but related surface: they don't try to make the agent treat data as
   instructions, they try to make a value's PROVENANCE look more trusted than
   it is (verbatim-planted attacker values inside an otherwise-legitimate,
   tool-sourced document). The paper itself flags "verbatim-copied untrusted
   values ... later treated as legitimately sourced" as a live concern — this
   is exactly the same same-observation-pollution class already tested
   against AuthGraph/RTBAS/Fides, now against CaMeL's policy layer too.
"""

from __future__ import annotations

import os
import sys
import json
import re
from dataclasses import dataclass, field
from typing import Any, Callable, Optional

